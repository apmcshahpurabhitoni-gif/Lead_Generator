-- LeadHunter: restore the search_results table used by Dashboard search history.
-- Safe to run repeatedly on an existing database.

create table if not exists search_results (
    id bigint generated by default as identity primary key,
    search_id bigint not null references jobs(id) on delete cascade,
    business_id bigint not null references businesses(id) on delete cascade,
    result_rank integer,
    created_at timestamptz default now(),
    unique (search_id, business_id)
);

create index if not exists idx_search_results_search_id
    on search_results (search_id);

create index if not exists idx_search_results_business_id
    on search_results (business_id);

create index if not exists idx_search_results_search_rank
    on search_results (search_id, result_rank);
